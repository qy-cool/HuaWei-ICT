"""Provision a single-node service and restore a trusted backup into a new, isolated instance."""

import argparse
import base64
from datetime import datetime, timezone
import hashlib
import ipaddress
import json
from pathlib import Path
import re
import secrets
import subprocess
import sys
import time
import uuid

IMAGES = {
    "postgres": "postgres:18.6-alpine3.23",
    "redis-cache": "redis:8.10.3-alpine",
    "redis-persistent": "redis:8.10.3-alpine",
    "rabbitmq": "rabbitmq:4.3.7-management",
}
PORTS = {"postgres": 5432, "redis-cache": 6379, "redis-persistent": 6379, "rabbitmq": 5672}
PAYLOADS = {"postgres": "orders.dump", "redis-cache": "cache.json",
            "redis-persistent": "dump.rdb", "rabbitmq": "topology.json"}
VHOST = "orders"
ADMIN = "cloide_admin"
APP = "orders_app"


def write_json(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def now():
    return datetime.now(timezone.utc).isoformat()


def digest(path):
    with path.open("rb") as file:
        return hashlib.file_digest(file, "sha256").hexdigest()


def cli(*args, **kwargs):
    return subprocess.run(args, check=True, timeout=kwargs.pop("timeout", 600), **kwargs)


def compose(root, *args, **kwargs):
    meta = read_json(root / "instance.json")
    # The project UUID is generated by init. Never infer a project from a cwd or a service name.
    project = "cloide-mw-" + str(uuid.UUID(meta["id"])).replace("-", "")
    return cli("docker", "compose", "-p", project, "-f", str(root / "compose.json"), *args, **kwargs)


def execute(root, *args, **kwargs):
    return compose(root, "exec", "-T", "service", *args, **kwargs)


def redis(root, *args, **kwargs):
    return execute(root, "sh", "-ec", 'export REDISCLI_AUTH="$(cat /run/secrets/admin)"; exec redis-cli -e "$@"',
                   "redis-cli", *args, **kwargs)


def password_hash(value):
    salt = secrets.token_bytes(4)
    return base64.b64encode(salt + hashlib.sha256(salt + value.encode()).digest()).decode()


def rabbit_definitions(admin_pw, app_pw):
    def user(name, password, tags):
        return {"name": name, "password_hash": password_hash(password), "hashing_algorithm": "rabbit_password_hashing_sha256", "tags": tags}

    return {
        "users": [user(ADMIN, admin_pw, "administrator"), user(APP, app_pw, "")],
        "vhosts": [{"name": VHOST}],
        "permissions": [
            {"user": ADMIN, "vhost": VHOST, "configure": ".*", "write": ".*", "read": ".*"},
            {"user": APP, "vhost": VHOST, "configure": "^$", "write": "^orders[.]events$", "read": "^orders[.]consumer$"},
        ],
        "exchanges": [{"name": name, "vhost": VHOST, "type": "direct", "durable": True,
                       "auto_delete": False, "internal": False, "arguments": {}} for name in ("orders.events", "orders.dead")],
        "queues": [{"name": "orders.consumer", "vhost": VHOST, "durable": True, "auto_delete": False,
                    "arguments": {"x-dead-letter-exchange": "orders.dead"}},
                   {"name": "orders.dead", "vhost": VHOST, "durable": True, "auto_delete": False, "arguments": {}}],
        "bindings": [{"source": exchange, "vhost": VHOST, "destination": queue, "destination_type": "queue",
                      "routing_key": "order.changed", "arguments": {}}
                     for exchange, queue in [("orders.events", "orders.consumer"), ("orders.dead", "orders.dead")]],
    }


def initialize(root, service, image, address=None, port=None):
    if service not in IMAGES:
        raise ValueError("未知服务模板")
    default = IMAGES[service]
    image = image or default
    # External manifests cannot choose an executable image; overrides must pin the same official repository by digest.
    repo = default.split(":")[0]
    if image != default and not re.fullmatch(re.escape(repo) + r"@sha256:[a-f0-9]{64}", image):
        raise ValueError("镜像必须是模板版本或相同官方仓库的内容摘要")
    if (address is None) != (port is None):
        raise ValueError("请同时指定业务网络 IP 和端口")
    if address is not None:
        ip = ipaddress.ip_address(address)
        if not ip.is_private or ip.is_unspecified or ip.is_multicast or not 1 <= port <= 65535:
            raise ValueError("请绑定具体的内网或回环地址及合法端口")

    root.mkdir(mode=0o700, parents=False, exist_ok=False)
    uid = str(uuid.uuid4())
    admin_pw, app_pw = secrets.token_hex(32), secrets.token_hex(32)
    for name, password in [("admin", admin_pw), ("app", app_pw)]:
        (root / name).write_text(password, encoding="ascii")
        (root / name).chmod(0o600)
    spec = {"image": image, "restart": "unless-stopped", "pids_limit": 256,
            "volumes": [], "secrets": ["admin"], "security_opt": ["no-new-privileges:true"]}
    if port is not None:
        spec["ports"] = [{"target": PORTS[service], "published": str(port), "host_ip": address}]
    if service == "postgres":
        spec["environment"] = {"POSTGRES_USER": ADMIN, "POSTGRES_DB": VHOST, "POSTGRES_PASSWORD_FILE": "/run/secrets/admin",
                               "PGDATA": "/var/lib/postgresql/18/docker"}
        # Mount the official PostgreSQL 18 volume root; explicit PGDATA also works for dumps restored on 18.
        spec["volumes"].append("data:/var/lib/postgresql")
        health = ["CMD", "pg_isready", "-q", "-U", ADMIN, "-d", VHOST]
    elif service.startswith("redis-"):
        persistent = service == "redis-persistent"
        config = [
            "bind 0.0.0.0", "protected-mode yes", "dir /data", "maxmemory 128mb",
            "user default on #" + hashlib.sha256(admin_pw.encode()).hexdigest() + " ~* &* +@all",
            "user " + APP + " on #" + hashlib.sha256(app_pw.encode()).hexdigest() + " ~* &* +@read +@write +@connection +@transaction -@dangerous",
            "maxmemory-policy " + ("noeviction" if persistent else "allkeys-lru"),
            "appendonly " + ("yes" if persistent else "no"), "appendfsync everysec",
            "save 300 100" if persistent else 'save ""',
        ]
        (root / "redis.conf").write_text("\n".join(config) + "\n", encoding="ascii")
        (root / "redis.conf").chmod(0o644)
        spec["volumes"].extend(["data:/data", "./redis.conf:/etc/cloide-redis.conf:ro"])
        spec["command"] = ["redis-server", "/etc/cloide-redis.conf"]
        health = ["CMD-SHELL", 'REDISCLI_AUTH="$$(cat /run/secrets/admin)" redis-cli --raw PING | grep -qx PONG']
    else:
        definition = root / "bootstrap.json"
        write_json(definition, rabbit_definitions(admin_pw, app_pw))
        definition.chmod(0o644)
        conf = root / "rabbitmq.conf"
        conf.write_text("definitions.import_backend = local_filesystem\ndefinitions.local.path = /etc/cloide-bootstrap.json\n", encoding="ascii")
        conf.chmod(0o644)
        spec["hostname"] = "orders"
        spec["environment"] = {"RABBITMQ_SERVER_ADDITIONAL_ERL_ARGS": "+S 2:2 +A 4"}
        spec["volumes"].extend(["data:/var/lib/rabbitmq", "./rabbitmq.conf:/etc/rabbitmq/conf.d/99-cloide.conf:ro",
                                "./bootstrap.json:/etc/cloide-bootstrap.json:ro"])
        # Management is loopback-only, on a free ephemeral host port, for authenticated topology operations.
        spec.setdefault("ports", []).append({"target": 15672, "host_ip": "127.0.0.1"})
        health = ["CMD", "rabbitmq-diagnostics", "-q", "check_running"]
    spec["healthcheck"] = {"test": health, "interval": "3s", "timeout": "6s", "retries": 35}
    write_json(root / "instance.json", {"id": uid, "service": service, "image": image, "createdAt": now()})
    write_json(root / "compose.json", {"services": {"service": spec}, "volumes": {"data": {}},
                                      "secrets": {"admin": {"file": "./admin"}}})


def up(root, restoring=False):
    restore = root / "restore.json"
    if not restoring and restore.exists() and read_json(restore)["state"] != "service_checked":
        raise ValueError("该实例恢复尚未验证，请保留现场并从新的空目录重新执行恢复")
    compose(root, "up", "-d", "--wait", "--wait-timeout", "150")
    if read_json(root / "instance.json")["service"] == "postgres":
        password = (root / "app").read_text(encoding="ascii")
        if not re.fullmatch(r"[a-f0-9]{64}", password):
            raise ValueError("应用凭据格式错误")
        sql = rf"""SELECT 'CREATE ROLE {APP} LOGIN' WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='{APP}') \gexec
ALTER ROLE {APP} PASSWORD '{password}';
ALTER DATABASE orders OWNER TO {APP};
ALTER SCHEMA public OWNER TO {APP};
"""
        execute(root, "psql", "-X", "-v", "ON_ERROR_STOP=1", "-U", ADMIN, "-d", VHOST,
                input=sql.encode(), stdout=subprocess.DEVNULL)


def topology(root, path="", method="GET", body=None):
    location = compose(root, "port", "service", "15672", capture_output=True, text=True).stdout.strip()
    return management_request(location, (root / "admin").read_text(), path, method, body)


def management_request(location, password, path, method="GET", body=None):
    import urllib.request
    if not re.fullmatch(r"127\.0\.0\.1:[0-9]{1,5}", location):
        raise ValueError("管理接口必须为本实例的回环地址")
    key = base64.b64encode((ADMIN + ":" + password).encode()).decode()
    request = urllib.request.Request("http://" + location + "/api/" + path, method=method,
                                     data=json.dumps(body).encode() if body is not None else None,
                                     headers={"Authorization": "Basic " + key, "Content-Type": "application/json"})
    # No proxies or redirects for local credentials.
    class NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, *args):
            return None
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())
    with opener.open(request, timeout=15) as response:
        raw = response.read()
        return json.loads(raw) if raw else None


def check(root):
    kind = read_json(root / "instance.json")["service"]
    if kind == "postgres":
        result = execute(root, "psql", "-XAt", "-U", ADMIN, "-d", VHOST, "-c", "SELECT current_database()", capture_output=True).stdout.strip()
        if result != b"orders": raise ValueError("业务库不可读")
    elif kind.startswith("redis-"):
        if redis(root, "--raw", "PING", capture_output=True).stdout.strip() != b"PONG":
            raise ValueError("Redis 鉴权或 PING 失败")
    else:
        info = topology(root, "queues/orders/orders.consumer")
        if not info["durable"] or info["arguments"].get("x-dead-letter-exchange") != "orders.dead":
            raise ValueError("业务队列或死信配置不符")


def backup(root, dest):
    meta = read_json(root / "instance.json")
    kind = meta["service"]
    check(root)
    dest.mkdir(mode=0o700, exist_ok=False)
    output = dest / PAYLOADS[kind]
    if kind == "postgres":
        with output.open("xb") as file:
            execute(root, "pg_dump", "-Fc", "--no-owner", "--no-acl", "-U", ADMIN, "-d", VHOST, stdout=file)
    elif kind == "redis-persistent":
        with output.open("xb") as file:
            redis(root, "--rdb", "-", stdout=file)
    elif kind == "redis-cache":
        write_json(output, {"restore": "empty-cache", "sourceOfTruth": "application"})
    else:
        write_json(output, topology(root, "definitions/orders"))
    container = compose(root, "ps", "-q", "service", capture_output=True, text=True).stdout.strip()
    image_id = cli("docker", "inspect", "--format", "{{.Image}}", container, capture_output=True, text=True).stdout.strip()
    write_json(dest / "manifest.json", {"schema": 1, "service": kind, "source": meta["id"], "createdAt": now(),
                                        "image": meta["image"], "imageId": image_id,
                                        "payload": output.name, "sha256": digest(output), "bytes": output.stat().st_size})


def restore_new(archive, root, image, address, port):
    meta = read_json(archive / "manifest.json")
    kind = meta["service"]
    if meta["schema"] != 1 or meta["payload"] != PAYLOADS[kind]:
        raise ValueError("备份清单类型错误")
    payload = archive / PAYLOADS[kind]
    if payload.is_symlink() or payload.stat().st_size != meta["bytes"] or digest(payload) != meta["sha256"]:
        raise ValueError("备份内容的摘要或大小不匹配")
    if (image or IMAGES[kind]) != meta["image"]:
        raise ValueError("请使用备份对应的已认可镜像；自定义摘要必须由管理员明确传入")
    local_image = cli("docker", "image", "inspect", "--format", "{{.Id}}", image or IMAGES[kind],
                      capture_output=True, text=True).stdout.strip()
    if local_image != meta["imageId"]:
        raise ValueError("本机镜像内容与备份记录不符，请先安装原镜像")
    initialize(root, kind, image, address, port)
    recipe = read_json(root / "compose.json")
    if port is not None:
        private = read_json(root / "compose.json")
        private["services"]["service"]["ports"] = [
            mapping for mapping in private["services"]["service"]["ports"] if mapping["target"] != PORTS[kind]
        ]
        write_json(root / "compose.json", private)
    write_json(root / "restore.json", {"state": "restoring", "source": meta["source"], "digest": meta["sha256"]})
    try:
        if kind == "redis-persistent":
            with payload.open("rb") as file:
                compose(root, "run", "--rm", "-T", "--no-deps", "--entrypoint", "sh", "service", "-ec",
                        'test ! -e /data/dump.rdb && test ! -e /data/appendonlydir; cat >/data/dump.rdb; redis-check-rdb /data/dump.rdb',
                        stdin=file, stdout=subprocess.DEVNULL)
            # Load the snapshot first. Redis otherwise prefers AOF on startup, including in a fresh volume.
            config = root / "redis.conf"
            original = config.read_text()
            config.write_text(original.replace("appendonly yes", "appendonly no"))
        up(root, restoring=True)
        if kind == "postgres":
            with payload.open("rb") as file:
                execute(root, "pg_restore", "-1", "--exit-on-error", "--no-owner", "--no-acl", "--role", APP,
                        "-U", ADMIN, "-d", VHOST, stdin=file)
        elif kind == "redis-persistent":
            redis(root, "CONFIG", "SET", "appendonly", "yes", stdout=subprocess.DEVNULL)
            deadline = time.monotonic() + 120
            while True:
                info = redis(root, "--raw", "INFO", "persistence", capture_output=True).stdout.splitlines()
                if all(line in info for line in [b"aof_enabled:1", b"aof_rewrite_in_progress:0",
                                                  b"aof_rewrite_scheduled:0", b"aof_last_bgrewrite_status:ok"]): break
                if time.monotonic() >= deadline: raise TimeoutError("AOF 重写未完成")
                time.sleep(.25)
            config.write_text(original)
            compose(root, "restart", "service")
            compose(root, "up", "-d", "--wait", "--wait-timeout", "120")
        elif kind == "rabbitmq":
            topology(root, "definitions/orders", "POST", read_json(payload))
        check(root)
        if port is not None:
            write_json(root / "compose.json", recipe)
            compose(root, "up", "-d", "--wait", "--wait-timeout", "150")
            check(root)
        write_json(root / "restore.json", {"state": "service_checked", "source": meta["source"],
                                           "digest": meta["sha256"], "finishedAt": now()})
    except BaseException:
        # A partial restoration remains private and cannot keep serving as if healthy. Preserve its volume for review.
        compose(root, "stop", "service", stdout=subprocess.DEVNULL)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="cmd", required=True)
    for command in ("init", "up", "check", "backup", "restore-new", "stop"):
        sub = commands.add_parser(command)
        sub.add_argument("directory", type=Path)
        if command == "init": sub.add_argument("service", choices=IMAGES)
        if command in ("init", "restore-new"):
            sub.add_argument("--image")
            sub.add_argument("--address")
            sub.add_argument("--port", type=int)
        if command in ("backup", "restore-new"): sub.add_argument("archive", type=Path)
    args = parser.parse_args()
    root = args.directory.resolve()
    if args.cmd == "init": initialize(root, args.service, args.image, args.address, args.port)
    elif args.cmd == "up": up(root)
    elif args.cmd == "check": check(root)
    elif args.cmd == "backup": backup(root, args.archive.resolve())
    elif args.cmd == "restore-new": restore_new(args.archive.resolve(), root, args.image, args.address, args.port)
    elif args.cmd == "stop": compose(root, "stop", "service")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError, subprocess.SubprocessError) as e:
        print(f"操作失败：{e}", file=sys.stderr)
        sys.exit(1)
